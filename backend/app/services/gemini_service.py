    def _chat_with_gemini(
        self,
        message: str,
        session: Any,
        effective_lang: str,
        detected_lang: str
    ) -> Dict[str, Any]:
        """Runs Gemini model with system instructions and tools."""
        model = self._client.GenerativeModel(
            model_name=self.model_name,
            system_instruction=SYSTEM_PROMPT
        )
        
        # Build prompt with active context
        ctx = session.context
        context_str = f"Active Selection Context: State='{ctx.get('state')}', Market='{ctx.get('market')}', Commodity='{ctx.get('commodity')}'. Target Response Language Code: '{effective_lang}'."
        full_prompt = f"{context_str}\n\nUser Question: {message}"

        response = model.generate_content(full_prompt)
        resp_text = response.text if response and response.text else "I am here to assist with your agricultural market queries."

        session.add_message(role="user", content=message, language=effective_lang)
        session.add_message(role="assistant", content=resp_text, language=effective_lang)

        return {
            "response": resp_text,
            "session_id": session.session_id,
            "language": effective_lang,
            "detected_language": detected_lang,
            "data": None,
            "tools_called": []
        }

